#!/usr/bin/env python3
"""Writes main/littlefs_image/games_table_dates.js: for the games table page
(gametable.html) the last-update date (from the git history of each game's
own files), its size in lines of code, and which games have an introduction
(intro_scripts.js). Run it before a release / when games change:

    python3 tools/games_table_dates.py

A game's own files are those that exist only for it: the shared engine
(game_knight.js and game_knightblocks.js under Rune Stones, Block Quest and
Inside the Chip; weapons_kit.js under the shooters; the page's shared layers)
are not counted for the games riding on them. Monster Hunt and Free drive
live inside cam.js: their dates come from the line range of their section
(git log -L).
"""
import datetime
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(HERE, "..", "main", "littlefs_image")
OUT = os.path.join(WEB, "games_table_dates.js")

FILES = {
    "demons": ["game_demons.js"],
    "david": ["game_david.js"],
    "poop": ["game_poop.js"],
    "coins": ["game_coins.js"],
    "codebreak": ["game_codebreak.js"],
    "sonar": ["game_sonar.js"],
    "echo": ["game_echo.js"],
    "crossing": ["game_crossing.js", "blockquest_gl.js"],
    "shepherd": ["game_shepherd.js"],
    "lightwall": ["game_lightwall.js"],
    "inkblot": ["game_inkblot.js"],
    "gems": ["game_gems.js"],
    "wisps": ["game_wisps.js"],
    "chips": ["game_chips.js"],
    "prisma": ["prisma_core.js", "prisma_levels.js", "game_prisma.js"],
    "temple": ["game_temple.js", "game_temple_sanctum.js", "game_temple_labyrinth.js", "game_temple_kit.js",
               "game_temple_sky.js", "game_temple_cistern.js", "game_temple_mirrors.js", "game_temple_vault.js"],
    "knight": ["game_knight.js"],
    "knightblocks": ["game_knightblocks.js"],
    "blockquest": ["blockquest_fx.js", "blockquest_gl.js", "blockquest_figures.js", "blockquest_actors.js", "game_blockquest.js", "blockquest_levels.js"],
    "runes": ["game_runes.js"],
    "nano": ["game_nano.js"],
    "race": ["game_race.js"],
    "scavenger": ["detect.js"],
    "detect": ["detect.js"],
    "focus": ["app_focus.js"],
    "camcal": ["camcal_solver.js", "camext_solver.js", "camservo.js", "app_camservo.js", "app_boardcheck.js", "app_camcal.js"],
    "none": ["freedrive_tags.js"],
}
# games that live inside cam.js: id -> (first line marker, last line marker)
IN_CAM = {"monster_hunt": ("// --- Fireball + monsters", "// --- Shared pose telemetry")}


def git(*args):
    return subprocess.run(["git", "-C", WEB, *args], capture_output=True, text=True, check=True).stdout.strip()


def lines_of(path):
    with open(os.path.join(WEB, path), encoding="utf-8") as f:
        return sum(1 for _ in f)


def main():
    games = {}
    for gid, files in FILES.items():
        dates = [git("log", "-1", "--format=%cs", "--", f) for f in files]
        dates = [d for d in dates if d]
        first = [git("log", "--format=%cs", "--", f).splitlines()[-1:] or [""] for f in files]
        games[gid] = {
            "updated": max(dates) if dates else None,
            "loc": sum(lines_of(f) for f in files),
            "files": len(files),
        }
    with open(os.path.join(WEB, "cam.js"), encoding="utf-8") as f:
        cam = f.read().split("\n")
    for gid, (a, b) in IN_CAM.items():
        i = next(n for n, l in enumerate(cam, 1) if l.startswith(a))
        j = next(n for n, l in enumerate(cam, 1) if l.startswith(b))
        d = git("log", "-1", "--format=%cs", "-s", "-L", f"{i},{j - 1}:cam.js")
        d = re.search(r"\d{4}-\d{2}-\d{2}", d)
        games[gid] = {"updated": d.group(0) if d else None, "loc": j - 1 - i, "files": 0, "inCam": True}
    with open(os.path.join(WEB, "intro_scripts.js"), encoding="utf-8") as f:
        intros = sorted(set(re.findall(r"^  I\.(\w+) = ", f.read(), re.M)))
    body = {"generated": datetime.date.today().isoformat(), "games": games, "intros": intros}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/games_table_dates.py (git history, line counts): don't edit by hand.\n")
        f.write("window.Lynx = window.Lynx || {};\nLynx.GAME_TABLE_DATES = ")
        json.dump(body, f, indent=1, sort_keys=True)
        f.write(";\n")
    print("wrote", OUT, len(games), "games")


if __name__ == "__main__":
    sys.exit(main())
